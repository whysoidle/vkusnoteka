import 'package:youtube_explode_dart/youtube_explode_dart.dart';
import 'import_job.dart';

class VideoSource {
  final String title, description, transcript;
  final List<String> warnings;
  const VideoSource({
    required this.title,
    this.description = '',
    this.transcript = '',
    this.warnings = const [],
  });
}

abstract class VideoSourceProvider {
  Future<VideoSource> load(String url, ImportJob job);
}

int captionPriority(ClosedCaptionTrackInfo track) {
  final language = track.language.code.split('-').first;
  return (language == 'ru'
          ? 0
          : language == 'en'
          ? 2
          : 4) +
      (track.isAutoGenerated ? 1 : 0);
}

class YouTubeSubtitles implements VideoSourceProvider {
  @override
  Future<VideoSource> load(String url, ImportJob job) async {
    final yt = YoutubeExplode();
    final unregister = job.onCancel(yt.close);
    var title = 'Рецепт из видео';
    var description = '';
    try {
      // Caption requests can succeed even if metadata is blocked.
      try {
        final video = await yt.videos
            .get(url)
            .timeout(const Duration(seconds: 25));
        title = video.title;
        description = video.description;
      } catch (_) {
        job.check();
      }
      job.check();
      final manifest = await yt.videos.closedCaptions
          .getManifest(url)
          .timeout(const Duration(seconds: 30));
      final tracks = manifest.tracks.toList()
        ..sort((a, b) => captionPriority(a).compareTo(captionPriority(b)));
      if (tracks.isEmpty) {
        return VideoSource(
          title: title,
          description: description,
          warnings: ['У видео нет доступных субтитров.'],
        );
      }
      final selected = tracks.first;
      final captions = await yt.videos.closedCaptions
          .get(selected)
          .timeout(const Duration(seconds: 30));
      job.check();
      final lines = <String>[];
      var previous = '';
      var length = 0;
      for (final caption in captions.captions) {
        final text = caption.text.replaceAll(RegExp(r'\s+'), ' ').trim();
        if (text.isEmpty || text == previous) continue;
        previous = text;
        final seconds = caption.offset.inSeconds;
        final timestamp =
            '${seconds ~/ 60}:${(seconds % 60).toString().padLeft(2, '0')}';
        final line = '[$timestamp] $text';
        length += line.length + 1;
        if (length > 60000) {
          return VideoSource(
            title: title,
            description: description,
            warnings: [
              'Субтитры превышают 60 000 символов. Вставьте в чат фрагмент с рецептом.',
            ],
          );
        }
        lines.add(line);
      }
      return VideoSource(
        title: title,
        description: description,
        transcript: lines.join('\n'),
        warnings: [
          if (selected.isAutoGenerated)
            'Использованы автоматические субтитры: проверьте названия продуктов и количества.',
        ],
      );
    } catch (_) {
      job.check();
      return VideoSource(
        title: title,
        description: description,
        warnings: [
          'Не удалось получить субтитры YouTube. Можно вставить их текст в чат или заполнить карточку вручную.',
        ],
      );
    } finally {
      unregister();
      yt.close();
    }
  }
}
