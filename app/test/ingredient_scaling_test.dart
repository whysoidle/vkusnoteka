import 'package:flutter_test/flutter_test.dart';
import 'package:recipe_vault/services/recipe_tools.dart';

void main() {
  void checkCases(Map<String, String> cases, {double factor = 2}) {
    for (final entry in cases.entries) {
      expect(
        scaleIngredient(entry.key, factor),
        entry.value,
        reason: entry.key,
      );
      expect(
        scaleIngredient(entry.key, 1),
        entry.key,
        reason: 'Reset preserves original',
      );
    }
  }

  test('quantity position, separators and spacing do not affect scaling', () {
    checkCases({
      '800 мл Куриный бульон': '1600 мл Куриный бульон',
      '• 800мл бульона': '• 1600мл бульона',
      'Куриный бульон 800 мл': 'Куриный бульон 1600 мл',
      'Бульон(800мл)': 'Бульон(1600мл)',
      'Яйца (2)': 'Яйца (4)',
      'Мука (200)': 'Мука (400)',
      '(1–2) яйца': '(2–4) яйца',
      'Бульон — 800 мл': 'Бульон — 1600 мл',
      'Бульон:800мл': 'Бульон:1600мл',
      'Бульон; 800 мл': 'Бульон; 1600 мл',
      'Бульон = 800 мл': 'Бульон = 1600 мл',
      'Бульон\n800 мл': 'Бульон\n1600 мл',
      'Бульон, около 800 мл': 'Бульон, около 1600 мл',
      'Мука — 200 г (1 стакан)': 'Мука — 400 г (2 стакан)',
      'Вода (мл): 800': 'Вода (мл): 1600',
      'Вода, мл 800': 'Вода, мл 1600',
      'Яйца 2': 'Яйца 4',
      '1. Мука, 200 г': '1. Мука, 400 г',
      '1.Мука, 200 г': '1.Мука, 400 г',
    });
  });

  test(
    'decimal, grouped, mixed and Unicode quantities retain useful precision',
    () {
      checkCases({
        'Молоко 0,5л': 'Молоко 1л',
        'Молоко 0.5 л': 'Молоко 1 л',
        'Молоко .5 л': 'Молоко 1 л',
        'Молоко ,5 л': 'Молоко 1 л',
        'Мука 1 000 г': 'Мука 2000 г',
        'Мука 1\u00a0000 г': 'Мука 2000 г',
        'Мука 1\u202f000,5 г': 'Мука 2001 г',
        'Мука 1.000,5 г': 'Мука 2001 г',
        'Мука 1,000.5 g': 'Мука 2001 g',
        'Сахар 1/2 ч. л.': 'Сахар 1 ч. л.',
        'Сахар 1 ⁄ 2 ч. л.': 'Сахар 1 ч. л.',
        'Мука 1 1/2 стакана': 'Мука 3 стакана',
        'Мука 1½ стакана': 'Мука 3 стакана',
        'Мука 1 ½ стакана': 'Мука 3 стакана',
        'Масло ¼ пачки': 'Масло 0,5 пачки',
        'Соль ½ ч/л': 'Соль 1 ч/л',
        'Сахар 1 ст.ложка': 'Сахар 2 ст.ложка',
        'Масло ⅜ пачки': 'Масло 0,75 пачки',
        'Дрожжи 0,005 г': 'Дрожжи 0,01 г',
        'Дрожжи 5e-3 г': 'Дрожжи 0,01 г',
        'Вода 0 мл': 'Вода 0 мл',
      });
      expect(scaleIngredient('Сахар ⅓ стакана', 3), 'Сахар 1 стакана');
      expect(scaleIngredient('Дрожжи 0,01 г', .25), 'Дрожжи 0,0025 г');
      expect(scaleIngredient('Сахар, 1/0 г', 2), 'Сахар, 1/0 г');
    },
  );

  test('ranges scale both endpoints with a shared or repeated unit', () {
    checkCases({
      'Мука 100–200г': 'Мука 200–400г',
      'Мука 100 - 200 г': 'Мука 200 - 400 г',
      'Мука от 100 до 200 г': 'Мука от 200 до 400 г',
      'Сахар, ½–¾ ч. л.': 'Сахар, 1–1,5 ч. л.',
      'Вода 0,5−0,75 л': 'Вода 1−1,5 л',
      'Масло 10 г – 20 г': 'Масло 20 г – 40 г',
      'Яйца: 1–2': 'Яйца: 2–4',
      'Чеснок от одной до двух головок': 'Чеснок от 2 до 4 головок',
    });
  });

  test('common quantities written in Russian words can be scaled', () {
    checkCases({
      'два яйца': '4 яйца',
      'Мука, двести пятьдесят граммов': 'Мука, 500 граммов',
      'Мука одна тысяча двести граммов': 'Мука 2400 граммов',
      'Молоко полтора литра': 'Молоко 3 литра',
      'Мука половина стакана': 'Мука 1 стакана',
      'Масло четверть пачки': 'Масло 0,5 пачки',
      'Вода поллитра': 'Вода 1 л',
      'Картофель полкило': 'Картофель 1 кг',
      'три яйца и два желтка': '6 яйца и 4 желтка',
      'Мука два с половиной стакана': 'Мука 5 стакана',
      'Мука 2 с четвертью стакана': 'Мука 4,5 стакана',
    });
  });

  test(
    'package count scales while explicitly stated size per package is fixed',
    () {
      checkCases({
        'Томаты — 2 банки по 400 г': 'Томаты — 4 банки по 400 г',
        'Томаты — 2 банки × 400 г': 'Томаты — 4 банки × 400 г',
        'Томаты — 2×400 г': 'Томаты — 4×400 г',
        'Сливки 2 x 200 мл': 'Сливки 4 x 200 мл',
        'Масло ½ пачки по 200 г': 'Масло 1 пачки по 200 г',
        'Томаты 1–2 банки по 400 г': 'Томаты 2–4 банки по 400 г',
        'Томаты две банки по 400 г': 'Томаты 4 банки по 400 г',
        'Томаты 2 банки (400 г каждая)': 'Томаты 4 банки (400 г каждая)',
        'Мука 2 пакета массой 1 кг': 'Мука 4 пакета массой 1 кг',
        'Бульон 2 банки по 400–500 мл': 'Бульон 4 банки по 400–500 мл',
      });
    },
  );

  test(
    'nutrition, names, ordinal indices and cooking attributes stay fixed',
    () {
      checkCases({
        'Сливки 20,5%, 100 мл': 'Сливки 20,5%, 200 мл',
        'Сливки 10–20% — 100 мл': 'Сливки 10–20% — 200 мл',
        'Мука сорта 1, 200 г': 'Мука сорта 1, 400 г',
        'Смесь 5 злаков, 100 г': 'Смесь 5 злаков, 200 г',
        'Сыр 4 сыра, 100 г': 'Сыр 4 сыра, 200 г',
        'Чай № 5, 2 ч. л.': 'Чай № 5, 4 ч. л.',
        'Витамин B12, 1 мг': 'Витамин B12, 2 мг',
        'Сыр 2 года выдержки, 100 г': 'Сыр 2 года выдержки, 200 г',
        'Вода 80°C — 200 мл': 'Вода 80°C — 400 мл',
        'Дрожжи, 5 г, оставить на 15 мин': 'Дрожжи, 10 г, оставить на 15 мин',
        'Соль, по вкусу': 'Соль, по вкусу',
        'Мука, количество не указано': 'Мука, количество не указано',
        'Сливки 20%': 'Сливки 20%',
        'Вода и молоко 1:1 (200 мл)': 'Вода и молоко 1:1 (400 мл)',
        'Вода 80–90°C — 200 мл': 'Вода 80–90°C — 400 мл',
      });
    },
  );

  test('invalid serving multipliers are rejected', () {
    for (final factor in [0.0, -1.0, double.nan, double.infinity]) {
      expect(() => scaleIngredient('Мука 200 г', factor), throwsArgumentError);
    }
  });
}
